class WordData {
  static const List<int> levels = [1, 2, 3, 4];

  static const Map<int, String> levelNames = {
    1: 'Level 1 (기초)',
    2: 'Level 2 (생활)',
    3: 'Level 3 (학교)',
    4: 'Level 4 (심화)',
  };

  static const Map<int, List<Word>> wordsByLevel = {
    1: _level1,
    2: _level2,
    3: _level3,
    4: _level4,
  };

  /// 단계 통과 기록을 남기는 영역 (모두 통과하면 그 Level '통과')
  static const List<String> categories = ['철자쓰기', '뜻고르기', '단어고르기', '듣고고르기'];

  /// 한 단계당 문제 수
  static const int perStage = 20;

  static String levelName(int level) => levelNames[level] ?? 'Level $level';

  static List<Word> getWords(int level) => wordsByLevel[level] ?? const [];

  static int getTotalStages(int level) {
    final n = getWords(level).length;
    return n == 0 ? 0 : (n + perStage - 1) ~/ perStage;
  }

  static List<Word> getStageWords(int level, int stage) {
    final all = getWords(level);
    final start = (stage - 1) * perStage;
    if (start < 0 || start >= all.length) return [];
    final end = (start + perStage) > all.length ? all.length : start + perStage;
    return all.sublist(start, end);
  }

  /// 단계 문제 수가 모자라면 같은 Level의 다른 단어로 채움
  static List<Word> getStageQuestions(int level, int stage, Random random) {
    final all = getWords(level);
    final items = List<Word>.from(getStageWords(level, stage));
    if (items.length < perStage) {
      final rest = all.where((w) => !items.contains(w)).toList()..shuffle(random);
      items.addAll(rest.take(perStage - items.length));
    }
    items.shuffle(random);
    return items;
  }
}
